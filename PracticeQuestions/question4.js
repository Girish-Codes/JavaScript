//Switch Case 1. Print the grade based on letter (A=Excellent, B=Good, C=Average, D=Poor).
let ch = 'A';

switch(ch) {
    case 'A':
        console.log("Excellent");
        break;
    case 'B':
        console.log("Good");
        break;
    case 'C':
        console.log("Average");
        break;
    case 'D':
        console.log("Poor");
        break;
    default:
        console.log("Invalid Option");
}